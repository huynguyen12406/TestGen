    /**
     * Parse sample code từ response thành SampleCode object.
     * 
     * @param response raw response từ AI
     * @param type loại code (AC, WA, TLE)
     * @param language ngôn ngữ lập trình
     * @return SampleCode object
     * @throws IOException nếu không extract được code
     */
    public static SampleCode parseSampleCode(String response, SampleCode.CodeType type, 
                                             SampleCode.Language language) throws IOException {
        if (response == null || response.isBlank()) {
            throw new IOException("ResponseParser parseSampleCode: Response is empty");
        }
        
        String code = extractCodeFromResponse(response);
        
        // Validate code contains expected patterns based on language
        boolean isValid = false;
        
        if (language == SampleCode.Language.CPP) {
            // C++ validation: check for #include and int main()
            boolean hasInclude = code.contains("#include");
            boolean hasMain = code.contains("int main()") || code.contains("int main(") || 
                             code.contains("int main (");
            isValid = hasInclude && hasMain;
        } else if (language == SampleCode.Language.JAVA) {
            // Java validation: check for class and main method
            boolean hasClass = code.contains("class Main") || code.contains("class Solution") || 
                              code.contains("public class") || code.contains("class ");
            boolean hasMain = code.contains("public static void main") || code.contains("void main");
            isValid = hasClass && hasMain;
        } else if (language == SampleCode.Language.PYTHON) {
            // Python validation: just check it's not empty and has some code structure
            isValid = code.contains("def ") || code.contains("if ") || code.contains("for ") || 
                     code.contains("while ") || code.contains("print(") || code.contains("input(");
        } else {
            // Unknown language - accept if not empty
            isValid = !code.trim().isEmpty();
        }
        
        if (!isValid) {
            // Try to provide more helpful error message
            String preview = code.length() > 100 ? code.substring(0, 100) + "..." : code;
            String expectedPattern = switch (language) {
                case CPP -> "#include and int main()";
                case JAVA -> "class and main method";
                case PYTHON -> "Python code structure (def, if, for, etc.)";
                default -> "valid code";
            };
            throw new IOException("ResponseParser parseSampleCode: Code validation failed - " +
                                  "Missing " + expectedPattern + ". Code may be incomplete or malformed. " +
                                  "Preview: " + preview);
        }
        
        SampleCode sampleCode = new SampleCode(type, language, code);
        
        // Extract explanation from comments if present
        String explanation = extractExplanationFromCode(code, type);
        if (explanation != null) {
            sampleCode.setExplanation(explanation);
        }
        
        return sampleCode;
    }
    
    // ===== HELPER METHODS =====
    
    /**
     * Extract JSON từ response, xử lý markdown code blocks.
     * 
     * Hỗ trợ các format:
     * - Pure JSON: {"key": "value"} hoặc [...]
     * - Markdown: ```json\n{"key": "value"}\n```
     * - Markdown: ```\n{"key": "value"}\n```
     * - Text before JSON: "Here is the JSON:\n\n[...]"
     */
    private static String extractJsonFromResponse(String response) {
        String cleaned = response.trim();
        
        // Case 1: Remove markdown code blocks FIRST (most common issue)
        if (cleaned.contains("```")) {
            // Find ALL code blocks and extract the largest one (likely the JSON)
            int firstBacktick = cleaned.indexOf("```");
            int lastBacktick = cleaned.lastIndexOf("```");
            
            if (firstBacktick != -1 && lastBacktick != -1 && firstBacktick < lastBacktick) {
                String betweenBackticks = cleaned.substring(firstBacktick + 3, lastBacktick);
                
                // Remove language identifier if present (json, javascript, etc.)
                betweenBackticks = betweenBackticks.trim();
                String lowerBetween = betweenBackticks.toLowerCase();
                
                // Check for language identifiers on first line
                String[] langIdentifiers = {"json", "javascript", "js"};
                for (String lang : langIdentifiers) {
                    if (lowerBetween.startsWith(lang)) {
                        int firstNewline = betweenBackticks.indexOf('\n');
                        if (firstNewline != -1) {
                            betweenBackticks = betweenBackticks.substring(firstNewline + 1);
                        }
                        break;
                    }
                }
                
                cleaned = betweenBackticks.trim();
            }
        }
        
        // Case 2: Remove common text prefixes before JSON
        String[] commonPrefixes = {
            "Here is the JSON:",
            "Here's the JSON:",
            "The JSON is:",
            "JSON:",
            "Đây là JSON:",
            "JSON như sau:",
            "Dưới đây là JSON:",
            "Response:",
            "Output:"
        };
        
        for (String prefix : commonPrefixes) {
            if (cleaned.toLowerCase().startsWith(prefix.toLowerCase())) {
                cleaned = cleaned.substring(prefix.length()).trim();
                break;
            }
        }
        
        // Case 3: Find JSON start ([ or {) - most reliable
        int jsonStart = -1;
        for (int i = 0; i < Math.min(cleaned.length(), 2000); i++) {
            char c = cleaned.charAt(i);
            if (c == '[' || c == '{') {
                jsonStart = i;
                break;
            }
        }
        
        if (jsonStart > 0) {
            cleaned = cleaned.substring(jsonStart);
        } else if (jsonStart == -1) {
            // No JSON found at all - return as is and let validation fail
            return cleaned;
        }
        
        // Case 4: Find JSON end (] or }) using bracket matching
        // This is more robust than just finding the last bracket
        int depth = 0;
        char startChar = cleaned.charAt(0); // Should be [ or {
        char endChar = (startChar == '[') ? ']' : '}';
        boolean inString = false;
        boolean escaped = false;
        int jsonEnd = -1;
        
        for (int i = 0; i < cleaned.length(); i++) {
            char c = cleaned.charAt(i);
            
            // Handle string escaping
            if (escaped) {
                escaped = false;
                continue;
            }
            
            if (c == '\\') {
                escaped = true;
                continue;
            }
            
            // Handle strings (don't count brackets inside strings)
            if (c == '"') {
                inString = !inString;
                continue;
            }
            
            if (inString) {
                continue;
            }
            
            // Count bracket depth
            if (c == startChar) {
                depth++;
            } else if (c == endChar) {
                depth--;
                if (depth == 0) {
                    jsonEnd = i + 1;
                    break;
                }
            }
        }
        
        if (jsonEnd > 0 && jsonEnd <= cleaned.length()) {
            cleaned = cleaned.substring(0, jsonEnd);
        }
        
        // Case 5: Remove any trailing text after JSON
        // Sometimes AI adds explanatory text after the JSON
        cleaned = cleaned.trim();
        
        return cleaned;
    }
    
    /**
     * Extract code từ response, xử lý markdown code blocks.
     * 
     * Hỗ trợ các format:
     * - Plain code: public class Solution { }
     * - Markdown: ```java\npublic class Solution { }\n```
     * - Markdown: ```\npublic class Solution { }\n```
     * - Text before code: "Here is the code:\n\npublic class Solution { }"
     */
    private static String extractCodeFromResponse(String response) throws IOException {
        String cleaned = response.trim();
        
        // Case 1: Remove markdown code blocks
        if (cleaned.contains("```")) {
            // Find first ``` and last ```
            int firstBacktick = cleaned.indexOf("```");
            int lastBacktick = cleaned.lastIndexOf("```");
            
            if (firstBacktick != -1 && lastBacktick != -1 && firstBacktick < lastBacktick) {
                // Extract content between first and last ```
                String betweenBackticks = cleaned.substring(firstBacktick + 3, lastBacktick);
                
                // Remove language identifier if present (java, cpp, python, etc.)
                betweenBackticks = betweenBackticks.trim();
                if (betweenBackticks.startsWith("java") || betweenBackticks.startsWith("cpp") || 
                    betweenBackticks.startsWith("python") || betweenBackticks.startsWith("c++")) {
                    int firstNewline = betweenBackticks.indexOf('\n');
                    if (firstNewline != -1) {
                        betweenBackticks = betweenBackticks.substring(firstNewline + 1);
                    }
                }
                
                cleaned = betweenBackticks.trim();
            }
        }
        
        // Case 2: Remove common text prefixes
        String[] commonPrefixes = {
            "Here is the code:",
            "Here's the code:",
            "The code is:",
            "Code:",
            "Solution:",
            "Đây là code:",
            "Code như sau:",
            "Giải pháp:"
        };
        
        for (String prefix : commonPrefixes) {
            if (cleaned.toLowerCase().startsWith(prefix.toLowerCase())) {
                cleaned = cleaned.substring(prefix.length()).trim();
                break;
            }
        }
        
        // Case 3: If code starts with explanatory text, try to find where actual code starts
        // Look for common Java code starting patterns
        String[] codeStartPatterns = {
            "import ",
            "package ",
            "public class ",
            "class ",
            "public interface ",
            "interface "
        };
        
        for (String pattern : codeStartPatterns) {
            int index = cleaned.indexOf(pattern);
            if (index > 0 && index < 200) { // Only if pattern found within first 200 chars
                // Check if there's text before this pattern
                String beforePattern = cleaned.substring(0, index).trim();
                // If text before pattern doesn't look like code, remove it
                if (!beforePattern.contains("{") && !beforePattern.contains(";")) {
                    cleaned = cleaned.substring(index);
                    break;
                }
            }
        }
        
        // Case 4: Remove trailing explanatory text after code
        // Look for common ending patterns
        String[] endPatterns = {
            "\n\nExplanation:",
            "\n\nNote:",
            "\n\nLưu ý:",
            "\n\nGiải thích:"
        };
        
        for (String endPattern : endPatterns) {
            int index = cleaned.indexOf(endPattern);
            if (index != -1) {
                cleaned = cleaned.substring(0, index);
                break;
            }
        }
        
        cleaned = cleaned.trim();
        
        if (cleaned.isEmpty()) {
            throw new IOException("ResponseParser extractCodeFromResponse: Code is empty after extraction");
        }
        
        return cleaned;
    }
    
