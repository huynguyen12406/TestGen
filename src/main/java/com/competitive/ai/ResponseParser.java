    /**
     * Parse response chứa nhiều code (AC, WA, TLE) được phân cách bằng ===TYPE===.
     * 
     * Format response từ AI:
     * ===AC===
     * #include <iostream>
     * ...
     * 
     * ===WA===
     * #include <iostream>
     * ...
     * 
     * ===TLE===
     * #include <iostream>
     * ...
     * 
     * @param response raw response từ AI
     * @param language ngôn ngữ lập trình
     * @return Map<CodeType, String> - map từ loại code sang source code
     * @throws IOException nếu không parse được
     */
    public static java.util.Map<SampleCode.CodeType, String> parseMultipleCodes(String response, 
                                                                                  SampleCode.Language language) throws IOException {
        if (response == null || response.isBlank()) {
            throw new IOException("ResponseParser parseMultipleCodes: Response is empty");
        }
        
        java.util.Map<SampleCode.CodeType, String> result = new java.util.HashMap<>();
        
        // Remove markdown code blocks nếu có
        String cleaned = response.trim();
        if (cleaned.contains("```")) {
            int firstBacktick = cleaned.indexOf("```");
            int lastBacktick = cleaned.lastIndexOf("```");
            
            if (firstBacktick != -1 && lastBacktick != -1 && firstBacktick < lastBacktick) {
                String betweenBackticks = cleaned.substring(firstBacktick + 3, lastBacktick);
                
                // Remove language identifier
                betweenBackticks = betweenBackticks.trim();
                if (betweenBackticks.startsWith("cpp") || betweenBackticks.startsWith("c++")) {
                    int firstNewline = betweenBackticks.indexOf('\n');
                    if (firstNewline != -1) {
                        betweenBackticks = betweenBackticks.substring(firstNewline + 1);
                    }
                }
                
                cleaned = betweenBackticks.trim();
            }
        }
        
        // Tìm các marker ===AC===, ===WA===, ===TLE===
        String[] markers = {"===AC===", "===WA===", "===TLE==="};
        SampleCode.CodeType[] types = {SampleCode.CodeType.AC, SampleCode.CodeType.WA, SampleCode.CodeType.TLE};
        
        for (int i = 0; i < markers.length; i++) {
            String marker = markers[i];
            SampleCode.CodeType type = types[i];
            
            int markerIndex = cleaned.indexOf(marker);
            if (markerIndex == -1) {
                // Marker không tìm thấy, skip
                continue;
            }
            
            // Tìm vị trí bắt đầu code (sau marker)
            int codeStart = markerIndex + marker.length();
            
            // Tìm vị trí kết thúc code (trước marker tiếp theo hoặc cuối string)
            int codeEnd = cleaned.length();
            for (int j = 0; j < markers.length; j++) {
                if (i != j) { // Không tìm chính marker hiện tại
                    int nextMarkerIndex = cleaned.indexOf(markers[j], codeStart);
                    if (nextMarkerIndex != -1 && nextMarkerIndex < codeEnd) {
                        codeEnd = nextMarkerIndex;
                    }
                }
            }
            
            // Extract code
            String code = cleaned.substring(codeStart, codeEnd).trim();
            
            // Validate code không rỗng
            if (code.isEmpty()) {
                throw new IOException("ResponseParser parseMultipleCodes: Code for " + type + " is empty");
            }
            
            // Validate code có cấu trúc cơ bản
            if (!code.contains("#include") && !code.contains("int main")) {
                throw new IOException("ResponseParser parseMultipleCodes: Code for " + type + 
                                      " is invalid - missing #include or main function");
            }
            
            result.put(type, code);
        }
        
        // Validate ít nhất có 1 code
        if (result.isEmpty()) {
            throw new IOException("ResponseParser parseMultipleCodes: No code found in response. " +
                                  "Expected markers: ===AC===, ===WA===, ===TLE===");
        }
        
        return result;
    }
