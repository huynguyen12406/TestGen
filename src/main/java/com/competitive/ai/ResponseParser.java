    // ===== 1. PARSE PROBLEM ANALYSIS =====
    
    /**
     * Parse JSON response từ AI thành Problem object.
     * 
     * @param response raw response từ AI (có thể là JSON thuần hoặc wrapped trong markdown)
     * @return Problem object với các fields đã được populate
     * @throws IOException nếu response không hợp lệ hoặc thiếu required fields
     */
    public static Problem parseProblemAnalysis(String response) throws IOException {
        if (response == null || response.isBlank()) {
            throw new IOException("ResponseParser parseProblemAnalysis: Response is empty");
        }
        
        // DEBUG: Log raw response (first 2000 chars)
        System.err.println("=== DEBUG: Raw AI Response for Problem Analysis (first 2000 chars) ===");
        System.err.println(response.substring(0, Math.min(response.length(), 2000)));
        System.err.println("=== Total length: " + response.length() + " chars ===");
        System.err.println("=== END DEBUG ===");
        
        // Extract JSON từ response (xử lý markdown code blocks)
        String cleanJson = extractJsonFromResponse(response);
        
        // DEBUG: Log cleaned JSON (first 2000 chars)
        System.err.println("=== DEBUG: Cleaned JSON (first 2000 chars) ===");
        System.err.println(cleanJson.substring(0, Math.min(cleanJson.length(), 2000)));
        System.err.println("=== Total length: " + cleanJson.length() + " chars ===");
        System.err.println("=== END DEBUG ===");
        
        if (!isValidJson(cleanJson)) {
            throw new IOException("ResponseParser parseProblemAnalysis: Invalid JSON format - " + 
                                  "Response may be incomplete or malformed");
        }
        
        try {
            JsonNode root = mapper.readTree(cleanJson);
            
            Problem problem = new Problem();
            
            // Parse các fields (hỗ trợ nhiều tên field khác nhau từ AI)
            problem.setTitle(getStringField(root, "title", "name", "problemName"));
            problem.setStatement(getStringField(root, "statement", "description", "problemStatement", "full_statement"));
            problem.setInputFormat(getStringField(root, "inputFormat", "input_format", "input"));
            problem.setOutputFormat(getStringField(root, "outputFormat", "output_format", "output"));
            problem.setConstraints(getStringField(root, "constraints", "constraint"));
            
            // Time limit - với validation linh hoạt
            String timeLimit = getStringField(root, "timeLimit", "time_limit", "timeLimitMs");
            if (timeLimit != null && !timeLimit.isBlank()) {
                // Normalize và check format
                String normalized = timeLimit.replaceAll("\\s+", "").toLowerCase();
                if (normalized.matches("\\d+(\\.\\d+)?(ms|s)?")) {
                    problem.setTimeLimit(timeLimit);
                } else {
                    // Format không hợp lệ, dùng default
                    problem.setTimeLimit("1s");
                }
            } else {
                problem.setTimeLimit("1s"); // Default nếu null hoặc blank
            }
            
            // Memory limit - với validation linh hoạt
            String memoryLimit = getStringField(root, "memoryLimit", "memory_limit");
            if (memoryLimit != null && !memoryLimit.isBlank()) {
                // Normalize và check format
                String normalized = memoryLimit.replaceAll("\\s+", "").toUpperCase();
                if (normalized.matches("\\d+MB")) {
                    problem.setMemoryLimit(memoryLimit);
                } else {
                    // Format không hợp lệ, dùng default
                    problem.setMemoryLimit("256MB");
                }
            } else {
                problem.setMemoryLimit("256MB"); // Default nếu null hoặc blank
            }
            
            // Optional fields
            String contestType = getStringField(root, "problemType", "contestType", "contest_type", "type");
            if (contestType != null) {
                problem.setContestType(contestType);
            }
            
            String examples = getStringField(root, "examples", "sampleIO", "sample_io");
            if (examples != null) {
                problem.setExamples(examples);
            }
            
            // Validate required fields
            validateProblemFields(problem);
            
            return problem;
            
        } catch (Exception e) {
            throw new IOException("ResponseParser parseProblemAnalysis: Failed to parse JSON - " + 
                                  e.getMessage() + " - AI response may be incomplete", e);
        }
    }
    
    /**
     * Validate rằng Problem object có đủ required fields.
     * Với ảnh, cho phép thiếu một số field và tự động điền giá trị mặc định.
     */
    private static void validateProblemFields(Problem problem) throws IOException {
        List<String> missingFields = new ArrayList<>();
        
        if (problem.getTitle() == null || problem.getTitle().isBlank()) {
            missingFields.add("title");
        }
        if (problem.getStatement() == null || problem.getStatement().isBlank()) {
            missingFields.add("statement");
        }
        
        // Cho phép thiếu inputFormat/outputFormat (có thể suy luận từ statement)
        if (problem.getInputFormat() == null || problem.getInputFormat().isBlank()) {
            problem.setInputFormat("Xem mô tả bài toán");
        }
        if (problem.getOutputFormat() == null || problem.getOutputFormat().isBlank()) {
            problem.setOutputFormat("Xem mô tả bài toán");
        }
        
        if (!missingFields.isEmpty()) {
            throw new IOException("ResponseParser parseProblemAnalysis: Missing required fields: " + 
                                  String.join(", ", missingFields) + " - AI response may be incomplete");
        }
    }
    
