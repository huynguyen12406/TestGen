    /**
     * Parse JSON array response thành List<Testcase>.
     * 
     * @param response raw response từ AI (JSON array)
     * @return List of Testcase objects
     * @throws IOException nếu response không hợp lệ
     */
    public static List<Testcase> parseTestcases(String response) throws IOException {
        if (response == null || response.isBlank()) {
            throw new IOException("ResponseParser parseTestcases: Response is empty");
        }
        
        // DEBUG: Log raw response (first 1000 chars)
        System.err.println("=== DEBUG: Raw AI Response (first 1000 chars) ===");
        System.err.println(response.substring(0, Math.min(response.length(), 1000)));
        System.err.println("=== END DEBUG ===");
        
        String cleanJson = extractJsonFromResponse(response);
        
        // DEBUG: Log cleaned JSON (first 1000 chars)
        System.err.println("=== DEBUG: Cleaned JSON (first 1000 chars) ===");
        System.err.println(cleanJson.substring(0, Math.min(cleanJson.length(), 1000)));
        System.err.println("=== END DEBUG ===");
        
        // Try to fix common JSON issues
        if (!isValidJson(cleanJson)) {
            System.err.println("=== DEBUG: JSON invalid, attempting auto-fix ===");
            
            // Common issue 1: Trailing comma before closing bracket
            String fixed = cleanJson.replaceAll(",\\s*]", "]").replaceAll(",\\s*}", "}");
            
            // Common issue 2: Missing closing bracket
            if (!fixed.trim().endsWith("]") && !fixed.trim().endsWith("}")) {
                if (fixed.trim().startsWith("[")) {
                    fixed = fixed.trim() + "]";
                } else if (fixed.trim().startsWith("{")) {
                    fixed = fixed.trim() + "}";
                }
            }
            
            // Common issue 3: Unescaped newlines in strings (should be \\n)
            // This is tricky - only fix if it's clearly wrong
            
            if (isValidJson(fixed)) {
                System.err.println("=== DEBUG: Auto-fix successful ===");
                cleanJson = fixed;
            } else {
                System.err.println("=== DEBUG: Auto-fix failed ===");
            }
        }
        
        if (!isValidJson(cleanJson)) {
            // Try to recover from truncated JSON (common when AI hits max_tokens)
            // Strategy: find the last complete JSON object and close the array
            System.err.println("=== DEBUG: Attempting truncated JSON recovery ===");
            
            String recovered = tryRecoverTruncatedJsonArray(cleanJson);
            if (recovered != null && isValidJson(recovered)) {
                System.err.println("=== DEBUG: Truncated JSON recovery successful ===");
                cleanJson = recovered;
            } else {
                // Provide more detailed error message
                String preview = cleanJson.length() > 200 ? cleanJson.substring(0, 200) + "..." : cleanJson;
                String endPreview = cleanJson.length() > 200 ? "..." + cleanJson.substring(cleanJson.length() - 200) : cleanJson;
                
                // Try to parse and get actual error
                String parseError = "Unknown";
                try {
                    mapper.readTree(cleanJson);
                } catch (Exception e) {
                    parseError = e.getMessage();
                }
                
                throw new IOException("ResponseParser parseTestcases: Invalid JSON format. " +
                                      "Parse error: " + parseError + "\n" +
                                      "Preview (start): " + preview + "\n" +
                                      "Preview (end): " + endPreview + "\n" +
                                      "Full response length: " + response.length() + " chars. " +
                                      "Cleaned JSON length: " + cleanJson.length() + " chars.");
            }
        }
        
        try {
            JsonNode root = mapper.readTree(cleanJson);
            
            if (!root.isArray()) {
                throw new IOException("ResponseParser parseTestcases: Expected JSON array but got object");
            }
            
            List<Testcase> testcases = new ArrayList<>();
            
            for (int i = 0; i < root.size(); i++) {
                JsonNode tcNode = root.get(i);
                
                Testcase tc = new Testcase();
                
                // ID (có thể từ AI hoặc tự generate)
                if (tcNode.has("id")) {
                    tc.setId(tcNode.get("id").asInt());
                } else {
                    tc.setId(i + 1);
                }
                
                // Input (required)
                String input = getStringField(tcNode, "input", "testInput", "in");
                if (input == null || input.isBlank()) {
                    throw new IOException("ResponseParser parseTestcases: Missing 'input' field in test case #" + (i + 1));
                }
                tc.setInput(input);
                
                // Expected Output (optional - AI có thể thiếu field này)
                String expectedOutput = getStringField(tcNode, "expectedOutput", "expected_output", 
                                                       "output", "expectedResult", "answer");
                if (expectedOutput == null || expectedOutput.isBlank()) {
                    // Nếu thiếu expectedOutput, dùng placeholder
                    // User sẽ cần verify test case này manually hoặc dùng verification workflow
                    System.err.println("=== WARNING: Test case #" + (i + 1) + " missing expectedOutput. Using placeholder. ===");
                    expectedOutput = "[MISSING - Please verify manually]";
                }
                tc.setExpectedOutput(expectedOutput);
                
                // Note (optional)
                String note = getStringField(tcNode, "note", "description", "type", "comment");
                if (note != null) {
                    tc.setNote(note);
                }
                
                // Mark as AI-generated
                tc.setGenerated(true);
                
                testcases.add(tc);
            }
            
            if (testcases.isEmpty()) {
                throw new IOException("ResponseParser parseTestcases: No test cases found in response");
            }
            
            return testcases;
            
        } catch (IOException e) {
            throw e; // Re-throw our custom IOExceptions
        } catch (Exception e) {
            throw new IOException("ResponseParser parseTestcases: Failed to parse JSON - " + 
                                  e.getMessage(), e);
        }
    }
    
